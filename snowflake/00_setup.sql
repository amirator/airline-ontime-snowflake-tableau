-- Snowflake deployment script (NOT executed: no Snowflake account was used for this project).
-- Shows how the same models would be loaded into Snowflake from an internal stage.
CREATE DATABASE IF NOT EXISTS AIRLINE_OTP;
CREATE SCHEMA IF NOT EXISTS AIRLINE_OTP.RAW;
CREATE OR REPLACE FILE FORMAT AIRLINE_OTP.RAW.PARQUET_FMT TYPE = PARQUET;
CREATE OR REPLACE STAGE AIRLINE_OTP.RAW.BTS_STAGE FILE_FORMAT = AIRLINE_OTP.RAW.PARQUET_FMT;
-- PUT file://data/parquet/*.parquet @AIRLINE_OTP.RAW.BTS_STAGE;   (run from SnowSQL)
CREATE OR REPLACE TABLE AIRLINE_OTP.RAW.ONTIME USING TEMPLATE (
  SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM TABLE(INFER_SCHEMA(
    LOCATION => '@AIRLINE_OTP.RAW.BTS_STAGE', FILE_FORMAT => 'AIRLINE_OTP.RAW.PARQUET_FMT')));
COPY INTO AIRLINE_OTP.RAW.ONTIME FROM @AIRLINE_OTP.RAW.BTS_STAGE
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
-- Then run models/snowflake/*.sql in numeric order as CREATE OR REPLACE VIEW/TABLE statements.
